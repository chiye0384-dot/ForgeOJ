export function readableJava(source) {
  const tokens=source.match(/"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|\/\/[^\n]*|\/\*[\s\S]*?\*\/|\s+|[^\s]/g)??[]
  let indent=0,parens=0,line='',out=[]
  const flush=()=>{if(line.trim())out.push('    '.repeat(Math.max(0,indent))+line.trim());line=''}
  for(const token of tokens){
    if(/^\s+$/.test(token)){if(line&&!line.endsWith(' '))line+=' ';continue}
    if(token.startsWith('//')){line+=token;flush();continue}
    if(token==='(')parens++
    if(token===')')parens--
    if(token==='}') {flush();indent--;line='}';flush();continue}
    line+=token
    if(token==='{'){flush();indent++}
    else if(token===';'&&parens===0)flush()
  }
  flush();return out.join('\n')+'\n'
}
